#!/usr/bin/env bash
#
# Package the prototype as a zip someone else can unpack and run.
#
#   ./scripts/package.sh              build the zip
#   ./scripts/package.sh --no-tests   skip the test run
#   ./scripts/package.sh --force      overwrite today's zip if it exists
#
# What goes in: source, tests, docs, requirements, .env.example.
# What stays out: .venv (690 MB), data/ (246 MB of derived artifacts), caches, and .env.
#
# The secret scan is the reason this is a script and not a zip command. The team contract
# says no keys ever leave the machine, .env holds three live ones, and "I remembered to
# exclude it" is not a control. This refuses to build a zip that contains a key, and it
# checks the built archive as well as the staging copy, so a mistake in the exclude list
# cannot slip past.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
NAME="talentflow-prototype"
STAMP="$(date +%Y%m%d)"
OUT="$(dirname "$ROOT")/${NAME}-${STAMP}.zip"

RUN_TESTS=1
FORCE=0
for arg in "$@"; do
  case "$arg" in
    --no-tests) RUN_TESTS=0 ;;
    --force)    FORCE=1 ;;
    -h|--help)  sed -n '2,12p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

say() { printf '  %s\n' "$*"; }
die() { printf '\nFAILED: %s\n' "$*" >&2; exit 1; }

echo
echo "Packaging $ROOT"

# ---------------------------------------------------------------- 1. tests
if [ "$RUN_TESTS" -eq 1 ]; then
  echo
  echo "Tests"
  if python3 -c "import pytest" 2>/dev/null; then
    ( cd "$ROOT" && python3 -m pytest tests/ -q -m "not slow" ) \
      || die "tests failed. Fix them, or pass --no-tests if you know why."
  else
    say "pytest not importable, skipping. Activate the venv to run them."
  fi
fi

# ---------------------------------------------------------------- 2. stage
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
DEST="$STAGE/$NAME"

echo
echo "Staging"
rsync -a \
  --exclude '.venv/' \
  --exclude 'data/' \
  --exclude 'docs/demos/*.mp4' \
  --exclude 'docs/demos/*.m4a' \
  --exclude 'docs/demos/*.mov' \
  --exclude '__pycache__/' \
  --exclude '.pytest_cache/' \
  --exclude '.git/' \
  --exclude '*.pyc' \
  --exclude '.DS_Store' \
  --exclude '.env' \
  "$ROOT/" "$DEST/"

[ -f "$DEST/.env" ] && die ".env reached the staging copy. Do not ship this."
[ -f "$DEST/requirements.txt" ] || die "requirements.txt missing from the staging copy."
[ -d "$DEST/talentflow" ] || die "the package has no talentflow/ directory."
say "$(find "$DEST" -type f | wc -l | tr -d ' ') files"

# ---------------------------------------------------------------- 3. secrets
# Prefixes, not entropy heuristics: a false positive costs one look, a miss costs a key.
echo
echo "Secret scan"
PATTERN='sk-ant-api[0-9]|sk-proj-[A-Za-z0-9_-]{20}|sk-[A-Za-z0-9]{32}|AIzaSy[A-Za-z0-9_-]{20}|ghp_[A-Za-z0-9]{20}'
if HITS=$(grep -rIEl "$PATTERN" "$DEST" 2>/dev/null); then
  echo "$HITS" | sed 's|'"$DEST"'|  |'
  die "a live-looking key is in the files above. Redact it, then run this again."
fi
say "no key patterns found in $(find "$DEST" -type f | wc -l | tr -d ' ') files"

# ---------------------------------------------------------------- 4. receipt
cat > "$DEST/PACKAGE_INFO.txt" <<INFO
TalentFlow prototype
Packaged $(date '+%Y-%m-%d %H:%M %Z') by scripts/package.sh

Not included, and why:

  .env        three live API keys. Copy .env.example to .env and add your own.
  .venv/      690 MB, and rebuilt in one command below.
  data/       246 MB of derived artifacts. Every file in it is regenerated by the
              pipeline. Nothing here is a source of truth.

To run it:

  python3 -m venv .venv && source .venv/bin/activate
  pip install -r requirements.txt
  cp .env.example .env        # then add a key if you want the LLM engine
  streamlit run app.py

The command-line pipeline, the stage order and the runtimes are in docs/PIPELINE.md.
Start with docs/HANDOFF.md.

The corpora themselves (Kaggle resumes, LinkedIn postings, O*NET) are not in this
archive and never were in the repository. Their locations are in talentflow/config.py.
INFO

# ---------------------------------------------------------------- 5. zip
echo
echo "Archive"
if [ -e "$OUT" ] && [ "$FORCE" -eq 0 ]; then
  die "$(basename "$OUT") already exists. Pass --force to replace it."
fi
[ -e "$OUT" ] && rm -f "$OUT"

( cd "$STAGE" && zip -q -r -X "$OUT" "$NAME" )

# Check the archive itself, not just what we meant to put in it.
unzip -Z1 "$OUT" | grep -qE '(^|/)\.env$' && die "the archive contains .env. Do not send it."
unzip -Z1 "$OUT" | grep -qE '(^|/)(\.venv|data)/' && die "the archive contains .venv or data/."
unzip -Z1 "$OUT" | grep -qiE '\.(mp4|m4a|mov|mkv|webm|wav)$' && die "the archive contains a recording. Keep audio and video out of the package."

echo
echo "Done"
say "$OUT"
say "$(du -h "$OUT" | cut -f1 | tr -d ' ')  $(unzip -Z1 "$OUT" | wc -l | tr -d ' ') entries"
say "sha256  $( (shasum -a 256 "$OUT" 2>/dev/null || sha256sum "$OUT") | cut -d' ' -f1)"
echo
